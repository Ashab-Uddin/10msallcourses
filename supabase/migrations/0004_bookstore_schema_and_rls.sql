  -- Strict Allowlist for book cover image URLs:
  --   1) NULL (no cover image)
  --   2) Canonical public https:// URL (ImageKit CDN / cloud storage)
  --   3) Strict project-owned relative /images/... path
  CONSTRAINT chk_books_cover_image_allowlist
    CHECK (
      cover_image IS NULL
      OR (
        char_length(cover_image) <= 2048
        AND position(chr(92) in cover_image) = 0
        AND cover_image ~ '^https://([A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?[.])+([A-Za-z]{2,63}|xn--[A-Za-z0-9-]{2,59})(:[0-9]{1,5})?([/?#][^[:space:][:cntrl:]]*)?$'
      )
      OR (
        char_length(cover_image) <= 512
        AND position('..' in cover_image) = 0
        AND cover_image ~ '^/images/[A-Za-z0-9][A-Za-z0-9._-]*(/[A-Za-z0-9][A-Za-z0-9._-]*)*$'
      )
    ),

  -- Strict Allowlist for book affiliate destination URL (empty or canonical https://)
  CONSTRAINT chk_books_affiliate_url_allowlist
    CHECK (
      affiliate_url = ''
      OR (
        char_length(affiliate_url) <= 2048
        AND position(chr(92) in affiliate_url) = 0
        AND affiliate_url ~ '^https://([A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?[.])+([A-Za-z]{2,63}|xn--[A-Za-z0-9-]{2,59})(:[0-9]{1,5})?([/?#][^[:space:][:cntrl:]]*)?$'
      )
    )
