CREATE OR REPLACE FUNCTION public.enforce_book_category_slug()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_cat_slug TEXT;
BEGIN
  SELECT bc.slug INTO v_cat_slug
  FROM public.book_categories bc
  WHERE bc.id = NEW.category_id;

  IF v_cat_slug IS NULL THEN
    RAISE EXCEPTION 'Invalid book category_id: %', NEW.category_id
      USING ERRCODE = 'foreign_key_violation';
  END IF;

  NEW.category_slug := v_cat_slug;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.sync_books_on_category_slug_change()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF NEW.slug IS DISTINCT FROM OLD.slug THEN
    UPDATE public.books
    SET category_slug = NEW.slug
    WHERE category_id = NEW.id;
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.increment_book_click(p_slug TEXT)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_new_count INTEGER;
BEGIN
  UPDATE public.books
  SET click_count = click_count + 1
  WHERE lower(slug) = lower(btrim(p_slug))
    AND status = 'active'
  RETURNING click_count INTO v_new_count;

  RETURN COALESCE(v_new_count, 0);
END;
$$;

