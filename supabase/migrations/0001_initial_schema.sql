BEGIN;

-- ----------------------------------------------------------------------------
-- 1. public.categories
-- Matches TypeScript `Category` interface (+ `updated_at` audit column)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.categories (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT        NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 120),
  slug          TEXT        NOT NULL UNIQUE CHECK (char_length(btrim(slug)) BETWEEN 1 AND 120),
  subtitle      TEXT        NULL CHECK (subtitle IS NULL OR char_length(subtitle) <= 250),
  badge_color   TEXT        NOT NULL DEFAULT 'red' CHECK (char_length(btrim(badge_color)) BETWEEN 1 AND 30),
  display_order INTEGER     NOT NULL DEFAULT 1 CHECK (display_order >= 0),
  status        TEXT        NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_categories_slug_lower
  ON public.categories (lower(slug));

CREATE INDEX IF NOT EXISTS idx_categories_status_order
  ON public.categories (status, display_order ASC, id ASC);

COMMENT ON TABLE public.categories IS 'Course categories displayed on public portal and managed in Admin Dashboard.';

-- ----------------------------------------------------------------------------
-- 2. public.courses
-- Matches ALL 30 fields of TypeScript `Course` interface 1:1
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.courses (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title               TEXT        NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 220),
  slug                TEXT        NOT NULL UNIQUE CHECK (char_length(btrim(slug)) BETWEEN 1 AND 220),
  category_id         BIGINT      NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT,
  category_slug       TEXT        NOT NULL CHECK (char_length(btrim(category_slug)) BETWEEN 1 AND 120),
  short_badge         TEXT        NOT NULL DEFAULT '' CHECK (char_length(short_badge) <= 60),
  header_title        TEXT        NOT NULL DEFAULT '10MS' CHECK (char_length(header_title) <= 80),
  header_subtitle     TEXT        NOT NULL DEFAULT 'অনলাইন কোর্স' CHECK (char_length(header_subtitle) <= 120),
  discount_badge_text TEXT        NOT NULL DEFAULT '' CHECK (char_length(discount_badge_text) <= 60),
  gradient_theme      TEXT        NOT NULL DEFAULT 'red' CHECK (char_length(btrim(gradient_theme)) BETWEEN 1 AND 40),
  description         TEXT        NOT NULL DEFAULT '' CHECK (char_length(description) <= 1000),
  full_description    TEXT        NULL CHECK (full_description IS NULL OR char_length(full_description) <= 5000),
  image_url           TEXT        NULL,
  image_fit           TEXT        NOT NULL DEFAULT 'contain' CHECK (image_fit IN ('contain', 'square', 'video', 'cover')),
  original_price      INTEGER     NOT NULL DEFAULT 0 CHECK (original_price >= 0),
  discount_price      INTEGER     NOT NULL DEFAULT 0 CHECK (discount_price >= 0),
  discount_percent    SMALLINT    NOT NULL DEFAULT 0 CHECK (discount_percent BETWEEN 0 AND 100),
  rating              TEXT        NOT NULL DEFAULT '৪.৯' CHECK (char_length(rating) <= 10),
  student_count       TEXT        NOT NULL DEFAULT '১০k+ শিক্ষার্থী' CHECK (char_length(student_count) <= 60),
  duration            TEXT        NOT NULL DEFAULT '৬ মাস' CHECK (char_length(duration) <= 60),
  target_students     TEXT        NOT NULL DEFAULT '' CHECK (char_length(target_students) <= 200),
  instructor_info     TEXT        NOT NULL DEFAULT '১০ মিনিট স্কুলের শীর্ষ শিক্ষক প্যানেল' CHECK (char_length(instructor_info) <= 200),
  instructor_icon     TEXT        NOT NULL DEFAULT 'school' CHECK (char_length(instructor_icon) <= 50),
  features            JSONB       NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(features) = 'array'),
  affiliate_url       TEXT        NOT NULL DEFAULT '',
  is_popular          BOOLEAN     NOT NULL DEFAULT true,
  status              TEXT        NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive', 'closed')),
  click_count         BIGINT      NOT NULL DEFAULT 0 CHECK (click_count >= 0),
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT chk_courses_discount_lte_original
    CHECK (original_price = 0 OR discount_price <= original_price),

  -- Strict Allowlist for course cover images:
  --   1) NULL (no custom image; UI gradient fallback)
  --   2) Canonical public https:// URL (ImageKit / 10MS CDN / cloud storage; no whitespace/control chars/backslash/IP/localhost)
  --   3) Strict project-owned relative path under /images/ only (no traversal '..', dotfiles, spaces, or protocol-relative '//')
  CONSTRAINT chk_courses_image_url_allowlist
    CHECK (
      image_url IS NULL
      OR (
        char_length(image_url) <= 2048
        AND position(chr(92) in image_url) = 0
        AND image_url ~ '^https://([A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?[.])+([A-Za-z]{2,63}|xn--[A-Za-z0-9-]{2,59})(:[0-9]{1,5})?([/?#][^[:space:][:cntrl:]]*)?$'
      )
      OR (
        char_length(image_url) <= 512
        AND position('..' in image_url) = 0
        AND image_url ~ '^/images/[A-Za-z0-9][A-Za-z0-9._-]*(/[A-Za-z0-9][A-Za-z0-9._-]*)*$'
      )
    ),

  -- Strict Allowlist for affiliate destination URL:
  --   Empty string '' OR canonical public https:// URL only (blocks http://, javascript:, data:, vbscript:, whitespace, control chars, backslash)
  CONSTRAINT chk_courses_affiliate_url_allowlist
    CHECK (
      affiliate_url = ''
      OR (
        char_length(affiliate_url) <= 2048
        AND position(chr(92) in affiliate_url) = 0
        AND affiliate_url ~ '^https://([A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?[.])+([A-Za-z]{2,63}|xn--[A-Za-z0-9-]{2,59})(:[0-9]{1,5})?([/?#][^[:space:][:cntrl:]]*)?$'
      )
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_courses_slug_lower
  ON public.courses (lower(slug));

CREATE INDEX IF NOT EXISTS idx_courses_status_created_at
  ON public.courses (status, created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_courses_category_id_status
  ON public.courses (category_id, status);

CREATE INDEX IF NOT EXISTS idx_courses_category_slug_status
  ON public.courses (category_slug, status);

CREATE INDEX IF NOT EXISTS idx_courses_popular_status
  ON public.courses (is_popular, status)
  WHERE is_popular = true;

COMMENT ON TABLE public.courses IS 'Affiliate courses catalog. Public visitors see active and closed courses; inactive courses are admin-only.';

-- ----------------------------------------------------------------------------
-- 3. public.click_records
-- Matches TypeScript `ClickRecord` interface (7 exact fields).
-- IMPORTANT:
--   - `id` is BIGINT to preserve existing 13-digit epoch-ms historical click IDs.
--   - `course_id` has NO blocking FK to `courses` so:
--       (a) All 9 existing historical click records survive migration with 0 courses.
--       (b) Deleting a course in the future NEVER deletes historical click analytics.
--   - Future clicks are strictly validated against active courses via server-only
--     RPC `public.record_active_course_click` in 0002_rls_and_functions.sql.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.click_records (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id    BIGINT      NOT NULL CHECK (course_id > 0),
  course_slug  TEXT        NOT NULL CHECK (char_length(btrim(course_slug)) BETWEEN 1 AND 220),
  course_title TEXT        NOT NULL CHECK (char_length(btrim(course_title)) BETWEEN 1 AND 220),
  referrer     TEXT        NULL CHECK (referrer IS NULL OR char_length(referrer) <= 300),
  user_agent   TEXT        NULL CHECK (user_agent IS NULL OR char_length(user_agent) <= 300),
  clicked_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_click_records_clicked_at_desc
  ON public.click_records (clicked_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_click_records_course_id
  ON public.click_records (course_id);

CREATE INDEX IF NOT EXISTS idx_click_records_course_slug
  ON public.click_records (course_slug);

COMMENT ON TABLE public.click_records IS 'Append-only affiliate click analytics preserving historical snapshots even after course deletion.';

-- ----------------------------------------------------------------------------
-- 4. public.inquiries
-- Matches TypeScript `CustomerInquiry` interface (7 exact fields)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.inquiries (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           TEXT        NOT NULL DEFAULT 'Anonymous' CHECK (char_length(btrim(name)) BETWEEN 1 AND 100),
  phone_or_email TEXT        NOT NULL DEFAULT '' CHECK (char_length(phone_or_email) <= 120),
  message        TEXT        NOT NULL CHECK (char_length(btrim(message)) BETWEEN 2 AND 2000),
  course_title   TEXT        NULL CHECK (course_title IS NULL OR char_length(course_title) <= 200),
  status         TEXT        NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'resolved')),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
