  site_title              TEXT        NOT NULL CHECK (char_length(btrim(site_title)) BETWEEN 1 AND 160),
  whatsapp_number         TEXT        NOT NULL DEFAULT '' CHECK (char_length(whatsapp_number) <= 40),
  whatsapp_link           TEXT        NOT NULL DEFAULT '',
  call_number             TEXT        NOT NULL DEFAULT '' CHECK (char_length(call_number) <= 40),
  messenger_link          TEXT        NOT NULL DEFAULT '',
  hero_badge              TEXT        NOT NULL DEFAULT '' CHECK (char_length(hero_badge) <= 200),
  hero_title              TEXT        NOT NULL DEFAULT '' CHECK (char_length(hero_title) <= 200),
  hero_subtitle           TEXT        NOT NULL DEFAULT '' CHECK (char_length(hero_subtitle) <= 500),
  show_countdown_timer    BOOLEAN     NOT NULL DEFAULT false,
  countdown_label         TEXT        NOT NULL DEFAULT '' CHECK (char_length(countdown_label) <= 200),
  countdown_target_course TEXT        NOT NULL DEFAULT 'all' CHECK (char_length(countdown_target_course) <= 120),
  countdown_target_date   TEXT        NOT NULL DEFAULT '' CHECK (char_length(countdown_target_date) <= 80),
  default_affiliate_ref   TEXT        NOT NULL DEFAULT '' CHECK (char_length(default_affiliate_ref) <= 120),
  updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- Strict Allowlist for WhatsApp link: empty string '' OR canonical public https:// URL
  CONSTRAINT chk_website_settings_whatsapp_link_allowlist
    CHECK (
      whatsapp_link = ''
      OR (
        char_length(whatsapp_link) <= 500
        AND position(chr(92) in whatsapp_link) = 0
        AND whatsapp_link ~ '^https://([A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?[.])+([A-Za-z]{2,63}|xn--[A-Za-z0-9-]{2,59})(:[0-9]{1,5})?([/?#][^[:space:][:cntrl:]]*)?$'
      )
    ),

  -- Strict Allowlist for Messenger link: empty string '' OR canonical public https:// URL
  CONSTRAINT chk_website_settings_messenger_link_allowlist
    CHECK (
      messenger_link = ''
      OR (
        char_length(messenger_link) <= 500
        AND position(chr(92) in messenger_link) = 0
        AND messenger_link ~ '^https://([A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?[.])+([A-Za-z]{2,63}|xn--[A-Za-z0-9-]{2,59})(:[0-9]{1,5})?([/?#][^[:space:][:cntrl:]]*)?$'
      )
    )
);

COMMENT ON TABLE public.website_settings IS 'Single-row website configuration (id = 1) matching all 15 SiteSettings fields.';

-- ----------------------------------------------------------------------------
-- 6. public.offer_timers
-- Matches TypeScript `OfferTimer` interface (course metadata hydrated via JOIN)
-- ON DELETE CASCADE ensures deleting a course automatically cleans up its timers
-- without affecting historical click_records.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.offer_timers (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id   BIGINT      NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
  offer_label TEXT        NOT NULL DEFAULT 'সীমিত সময়ের স্পেশাল অফার!' CHECK (char_length(btrim(offer_label)) BETWEEN 1 AND 160),
  start_at    TIMESTAMPTZ NOT NULL,
  end_at      TIMESTAMPTZ NOT NULL,
  is_paused   BOOLEAN     NOT NULL DEFAULT false,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT chk_offer_timers_window CHECK (end_at > start_at)
);

CREATE INDEX IF NOT EXISTS idx_offer_timers_course_id
  ON public.offer_timers (course_id);

CREATE INDEX IF NOT EXISTS idx_offer_timers_active_lookup
  ON public.offer_timers (is_paused, end_at DESC);

COMMENT ON TABLE public.offer_timers IS 'Scheduled/active promotional countdown timers linked to courses (CASCADE delete on course removal).';

-- ----------------------------------------------------------------------------
-- 7. public.admin_users
-- Supabase Auth Admin Authorization Allowlist (maps auth.users.id -> admin role)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.admin_users (
  user_id      UUID        PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email        TEXT        NOT NULL UNIQUE CHECK (char_length(btrim(email)) BETWEEN 3 AND 255),
  display_name TEXT        NOT NULL DEFAULT 'Site Admin' CHECK (char_length(btrim(display_name)) BETWEEN 1 AND 120),
  role         TEXT        NOT NULL DEFAULT 'admin' CHECK (role IN ('admin', 'super_admin')),
  is_active    BOOLEAN     NOT NULL DEFAULT true,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_admin_users_email_lower
  ON public.admin_users (lower(email));

CREATE INDEX IF NOT EXISTS idx_admin_users_active
  ON public.admin_users (user_id)
  WHERE is_active = true;

COMMENT ON TABLE public.admin_users IS 'Authorized Supabase Auth administrators allowed to access Admin Dashboard and execute admin RLS policies.';

