BEGIN;

CREATE TABLE IF NOT EXISTS public.course_features (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id  BIGINT      NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
  title      TEXT        NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 300),
  icon       TEXT        NOT NULL DEFAULT 'check' CHECK (
    icon IN ('tag', 'laptop', 'help', 'file', 'clock', 'book', 'award', 'check')
  ),
  sort_order INTEGER     NOT NULL DEFAULT 1 CHECK (sort_order >= 1),
  is_active  BOOLEAN     NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_course_features_course_order
  ON public.course_features (course_id, sort_order ASC, id ASC);

CREATE INDEX IF NOT EXISTS idx_course_features_active_lookup
  ON public.course_features (course_id, sort_order ASC, id ASC)
  WHERE is_active = true;

COMMENT ON TABLE public.course_features IS 'Dynamic, sortable, publishable course feature items displayed under "এই কোর্সে যা যা থাকছে" on Course Cards and Details Modal.';

DROP TRIGGER IF EXISTS trg_course_features_set_updated_at ON public.course_features;
CREATE TRIGGER trg_course_features_set_updated_at
  BEFORE UPDATE ON public.course_features
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

REVOKE ALL ON TABLE public.course_features FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.course_features_id_seq FROM PUBLIC, anon, authenticated;

GRANT SELECT ON TABLE public.course_features TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.course_features TO authenticated;
GRANT ALL ON TABLE public.course_features TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.course_features_id_seq TO authenticated, service_role;

ALTER TABLE public.course_features ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS course_features_public_read ON public.course_features;
CREATE POLICY course_features_public_read
  ON public.course_features
  FOR SELECT
  TO anon, authenticated
  USING (
    is_active = true
    AND EXISTS (
      SELECT 1
      FROM public.courses c
      WHERE c.id = course_features.course_id
        AND c.status IN ('active', 'closed')
    )
  );

DROP POLICY IF EXISTS course_features_admin_all ON public.course_features;
CREATE POLICY course_features_admin_all
  ON public.course_features
  FOR ALL
  TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

-- Safe one-time backfill for any course that has JSONB `features` entries and no rows in `public.course_features` yet
INSERT INTO public.course_features (course_id, title, icon, sort_order, is_active)
SELECT
  c.id AS course_id,
  btrim(elem.val) AS title,
  CASE
    WHEN lower(elem.val) ~ '(ফি|৳|ছাড়|ডিসকাউন্ট|অফার|fee|discount)' THEN 'tag'
    WHEN lower(elem.val) ~ '(এক্সাম|পরীক্ষা|qna|সলভ|ডাউট|মক|টেস্ট|quiz|exam)' THEN 'help'
    WHEN lower(elem.val) ~ '(শিট|নোট|পিডিএফ|pdf|sheet|সাজেশন|প্রশ্নব্যাংক)' THEN 'file'
    WHEN lower(elem.val) ~ '(বই|মাস্টারবুক|সিলেবাস|book|syllabus)' THEN 'book'
    WHEN lower(elem.val) ~ '(পর্যন্ত|সময়|মাস|মেয়াদ|ভর্তি|চলমান|duration)' THEN 'clock'
    WHEN lower(elem.val) ~ '(লাইভ|ক্লাস|প্রস্তুতি|বিষয়|রেকর্ড|live|class|board)' THEN 'laptop'
    WHEN lower(elem.val) ~ '(শিক্ষক|মেন্টর|সার্টিফিকেট|গাইড|mentor|certificate)' THEN 'award'
    ELSE (ARRAY['tag', 'laptop', 'help', 'file', 'clock', 'check'])[((elem.ord::integer - 1) % 6) + 1]
  END AS icon,
  elem.ord::integer AS sort_order,
  true AS is_active
FROM public.courses c
CROSS JOIN LATERAL jsonb_array_elements_text(
  CASE
    WHEN jsonb_typeof(c.features) = 'array' THEN c.features
    ELSE '[]'::jsonb
  END
) WITH ORDINALITY AS elem(val, ord)
WHERE char_length(btrim(elem.val)) BETWEEN 1 AND 300
  AND NOT EXISTS (
    SELECT 1
    FROM public.course_features cf
    WHERE cf.course_id = c.id
  );

COMMIT;
