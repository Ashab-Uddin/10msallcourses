DROP POLICY IF EXISTS online_batch_courses_admin_all ON public.online_batch_courses;
CREATE POLICY online_batch_courses_admin_all
  ON public.online_batch_courses
  FOR ALL
  TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

