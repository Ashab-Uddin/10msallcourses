-- ----------------------------------------------------------------------------
-- 1. public.online_batch_classes
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.online_batch_classes (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_key     TEXT        NOT NULL UNIQUE CHECK (char_length(btrim(class_key)) BETWEEN 1 AND 80),
  name          TEXT        NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 120),
  section_title TEXT        NOT NULL CHECK (char_length(btrim(section_title)) BETWEEN 1 AND 160),
  badge_text    TEXT        NOT NULL DEFAULT '' CHECK (char_length(badge_text) <= 40),
  subtitle      TEXT        NULL CHECK (subtitle IS NULL OR char_length(subtitle) <= 250),
  theme         TEXT        NOT NULL DEFAULT 'indigo'
                            CHECK (theme IN ('indigo', 'emerald', 'teal', 'purple', 'orange', 'blue', 'rose')),
  icon_key      TEXT        NOT NULL DEFAULT 'graduation-cap' CHECK (char_length(icon_key) <= 40),
  category_slug TEXT        NULL CHECK (category_slug IS NULL OR char_length(category_slug) <= 120),
  display_order INTEGER     NOT NULL DEFAULT 1 CHECK (display_order >= 0),
  status        TEXT        NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_online_batch_classes_key_lower
  ON public.online_batch_classes (lower(class_key));

CREATE INDEX IF NOT EXISTS idx_online_batch_classes_status_order
  ON public.online_batch_classes (status, display_order ASC, id ASC);

COMMENT ON TABLE public.online_batch_classes IS 'Academic Online Batch classes (e.g., Class 6-10 / SSC 28 / SSC 29) managed by Admins.';

-- ----------------------------------------------------------------------------
-- 2. public.online_batch_courses
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.online_batch_courses (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_class_id BIGINT      NOT NULL REFERENCES public.online_batch_classes(id) ON DELETE CASCADE,
  course_id      BIGINT      NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
  custom_badge   TEXT        NOT NULL DEFAULT '' CHECK (char_length(custom_badge) <= 60),
  display_order  INTEGER     NOT NULL DEFAULT 1 CHECK (display_order >= 0),
  status         TEXT        NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT uq_online_batch_class_course UNIQUE (batch_class_id, course_id)
);

CREATE INDEX IF NOT EXISTS idx_online_batch_courses_class_order
  ON public.online_batch_courses (batch_class_id, status, display_order ASC, id ASC);

CREATE INDEX IF NOT EXISTS idx_online_batch_courses_course_id
  ON public.online_batch_courses (course_id);

COMMENT ON TABLE public.online_batch_courses IS 'Ordered mapping between Online Batch classes and courses.';

-- ----------------------------------------------------------------------------
-- 3. Timestamp Triggers
-- ----------------------------------------------------------------------------
DROP TRIGGER IF EXISTS trg_online_batch_classes_set_updated_at ON public.online_batch_classes;
CREATE TRIGGER trg_online_batch_classes_set_updated_at
  BEFORE UPDATE ON public.online_batch_classes
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_online_batch_courses_set_updated_at ON public.online_batch_courses;
CREATE TRIGGER trg_online_batch_courses_set_updated_at
  BEFORE UPDATE ON public.online_batch_courses
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

-- ----------------------------------------------------------------------------
-- 4. Least-Privilege GRANTs & Row Level Security (RLS)
-- ----------------------------------------------------------------------------
REVOKE ALL ON TABLE public.online_batch_classes FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.online_batch_courses FROM PUBLIC, anon, authenticated;

GRANT SELECT ON TABLE public.online_batch_classes TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON TABLE public.online_batch_classes TO authenticated;
GRANT ALL ON TABLE public.online_batch_classes TO service_role;

GRANT SELECT ON TABLE public.online_batch_courses TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON TABLE public.online_batch_courses TO authenticated;
GRANT ALL ON TABLE public.online_batch_courses TO service_role;

GRANT USAGE, SELECT ON SEQUENCE public.online_batch_classes_id_seq TO authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.online_batch_courses_id_seq TO authenticated, service_role;

ALTER TABLE public.online_batch_classes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.online_batch_courses ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS online_batch_classes_public_select_active ON public.online_batch_classes;
CREATE POLICY online_batch_classes_public_select_active
  ON public.online_batch_classes
  FOR SELECT
  TO anon, authenticated
  USING (status = 'active');

DROP POLICY IF EXISTS online_batch_classes_admin_all ON public.online_batch_classes;
CREATE POLICY online_batch_classes_admin_all
  ON public.online_batch_classes
  FOR ALL
  TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS online_batch_courses_public_select_active ON public.online_batch_courses;
CREATE POLICY online_batch_courses_public_select_active
  ON public.online_batch_courses
  FOR SELECT
  TO anon, authenticated
